"""Build the markdown results tables from the CSVs written by run_all.py.
Usage: python3 -I make_report.py <results_dir> <out_md>
The narrative sections (findings, limitations) are written by hand in the final document; this script produces
the data-driven tables so the numbers in the report are reproducible from the CSVs.
"""
import sys, os, json
import numpy as np, pandas as pd

import glob
res, out_md = sys.argv[1], sys.argv[2]


def load(stem):
    files = sorted(glob.glob(os.path.join(res, f'{stem}*.csv')))
    return pd.concat([pd.read_csv(f) for f in files], ignore_index=True)


master, by_year, by_sess, by_half, rnd = (load(s) for s in ('master', 'by_year', 'by_session', 'by_half', 'random'))
info = {}
for f in sorted(glob.glob(os.path.join(res, 'run_info*.json'))):
    info.update(json.load(open(f)))

UNIT = {'EURUSD': 'pips', 'XAUUSD': 'points ($0.01)'}
ORDER = ['gross', 'cheap', 'base', 'expensive']


def f(x, d=2):
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return 'inf' if isinstance(x, float) and np.isinf(x) else '-'
    return f'{x:,.{d}f}'


def ci(lo, hi, d=2):
    if np.isnan(lo):
        return '-'
    s = f'[{lo:+.{d}f}, {hi:+.{d}f}]'
    return s + (' *' if lo > 0 else '')


def md_table(rows, header):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '|'.join(['---'] * len(header)) + '|']
    for r in rows:
        lines.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    return '\n'.join(lines)


HEADER = r"""# Independent backtest of common retail scalping strategies on EURUSD and XAUUSD (M1/M5), Jan 2024 - Nov 2026

*Prepared 5 November 2026. Everything below was computed from raw minute data with the code in `backtest_code/`; no vendor backtests, Myfxbook pages or marketing claims were used. The tables are generated by `make_report.py` from the result CSVs, so every number is reproducible.*

## 1. Data

### 1.1 What was tried, in order

1. **HistData.com** (free ASCII M1). The download page's hidden form (`POST /get.php` with `tk, date, datemonth, platform, timeframe, fxpair`) is served with an **empty `tk` token** to non-interactive clients and the POST returns a 0-byte body. It could not be used without impersonating a browser, which was not done.
2. **Dukascopy** (`datafeed.dukascopy.com/.../BID_candles_min_1.bi5`). Reachable, and the files decode correctly (LZMA, 24-byte big-endian records), but the endpoint rate-limits scripted clients hard: 1 of 6 requests at 2-second spacing succeeded, the rest returned HTTP 429 pointing to their data-export wiki. The `dukascopy-python` package works only by spoofing a Chrome user agent and a widget referer, so it was not used. Dukascopy was used only for **three day-files (EURUSD 2025-01-03, XAUUSD 2025-01-10, XAUUSD 2025-07-10)** to cross-validate the primary source.
3. **Forexite** free daily archives (`forexite.com/free_forex_quotes/YYYY/MM/DDMMYY.zip`) - **this is the source used.** 1,047 daily files, 2023-12-24 to 2026-11-04, zero missing days, zero unreadable files. Each file holds M1 bars for ~67 instruments; EURUSD and XAUUSD were extracted.

### 1.2 Forexite data characteristics (verified against Dukascopy, not assumed)

* **Quote type: bid** (the archive is the "ProSuite Bid" set on the Forexite page). Cross-check against Dukascopy bid candles: mean difference EURUSD -1.4 pips (a constant offset - Forexite's dealing-desk bid sits slightly below interbank bid; irrelevant for bid-to-bid P&L), XAUUSD -$0.001.
* **Timezone: Europe/Berlin local time (GMT+1 winter, GMT+2 summer); stamps are bar-close times.** Established by aligning minute returns with Dukascopy: best shift -1h -1min in January (return correlation 0.83 EURUSD, 0.95 gold) and -2h -1min in July (0.96 gold). Everything in this study was converted to **UTC bar-open time**.
* **Price resolution: 4 decimals for EURUSD (whole pips, no pipettes) and 1 decimal for XAUUSD ($0.10).** This is the most important data limitation: highs and lows are rounded to 1 pip / 10 points, so intrabar stop and target touches carry about +/-0.5 pip / +/-5 points of rounding noise. Combined with the engine's conservative tie-break (both levels touched in one bar = loss) this biases M1 results slightly against the strategies: the random baseline's *gross* M1 expectancy is about -0.1 pip instead of 0 (it is 0 on M5).
* **No volume.** Forexite provides none, so the VWAP strategy (H) is a time-weighted session average (TWAP) with +/-2 sigma bands.

### 1.3 Coverage after cleaning

| Symbol | M1 bars | First bar (UTC) | Last bar (UTC) | Weekdays with data from 2024-01-01 | Duplicate timestamps / inconsistent OHLC rows |
|---|---|---|---|---|---|
| EURUSD | 1,074,945 | 2023-12-24 22:00 | 2026-11-04 22:59 | 743 | 0 / 0 |
| XAUUSD | 1,068,700 | 2023-12-24 22:00 | 2026-11-04 22:59 | 743 | 0 / 0 |

Months covered: **2024-01 through 2026-11** (2026-11 = 1-4 November only), i.e. 35 months; the last week of December 2023 is used only as indicator warm-up and no trade before 2024-01-01 is counted. Roughly 29,000-33,000 M1 bars per month per symbol (trading week Sunday 22:00 UTC to Friday 22:00 UTC; no gaps longer than 60 minutes inside the trading week).

## 2. Cost assumptions

Costs are deducted once per round trip from the gross result. Spread is charged in full (enter at ask, exit at bid, on bid data), commission is converted to pips/points per lot, slippage is charged on both fills.

| Symbol | Case | Spread | Commission | Slippage per side | **Round-trip total** |
|---|---|---|---|---|---|
| EURUSD | cheap | 0.1 pip raw ECN | $7/lot RT = 0.7 pip | 0 | **0.8 pip** |
| EURUSD | **base** | 0.1 pip raw ECN | 0.7 pip | 0.2 pip | **1.2 pips** |
| EURUSD | expensive | 1.5 pips "standard" account | 0 | 0.3 pip | **2.1 pips** |
| XAUUSD | cheap | 10 points ($0.10) | $7/lot = 7 points | 4 points | **25 points ($0.25)** |
| XAUUSD | **base** | 15 points ($0.15) | 7 points | 10 points | **42 points ($0.42)** |
| XAUUSD | expensive | 30 points ($0.30) "standard" | 0 | 10 points | **50 points ($0.50)** |

A **gross** case (zero cost) is also reported so the edge of the signal itself can be separated from the cost drag. Not modelled: variable spreads (news spikes and the 21:00-22:00 UTC rollover widening are real and would hurt Asia-session and breakout trades further), swap on the few trades held overnight, requotes, broker minimum-stop-level rules, partial fills.

## 3. Methodology

* **Bars:** M1 as delivered; M5 built from M1 on UTC 5-minute boundaries (open = first, high = max, low = min, close = last).
* **Indicators** follow MT5 definitions: EMA (recursive, `span = n`), ATR(14) = SMA of true range, RSI = Wilder smoothing, Bollinger(20, 2) with population standard deviation, Stochastic(5,3,3) = SMA-slowed %K and SMA %D. Indicators are computed on the signal timeframe from closed bars only.
* **Fills:** a signal on the close of bar *t* fills at the **open of bar t+1** (for M5 signals: the first M1 bar at or after the M5 bar's close). Stop orders (strategies C, D) fill at the stop level, or at the bar's open if the bar gaps through it. Entry prices were checked against the bar data (`sanity_check.py`).
* **Exits:** SL/TP are checked on every M1 bar from the entry bar onward using high/low. **If both are touched in the same M1 bar the trade counts as a loss.** A bar opening beyond the stop exits at the open. Time/signal exits execute at the open of the exit bar. Any trade still open at the end of the data is closed at the last close.
* **Position handling:** one position per strategy variant at a time; signals during an open position are ignored. Fixed 1 lot for pip accounting. A **minimum stop distance of one data tick (1 pip / $0.10)** is enforced: ATR-based stops tighter than that are widened to one tick and the share of such trades is recorded; without this the R-multiples of M1 strategies in quiet hours are meaningless (stops of 0.2 pip).
* **Sizing for the % figures:** $10,000 start, 1% of current equity risked per trade (lots = risk $ / (stop distance x pip value)), capped at 30:1 (EURUSD) / 20:1 (XAUUSD) leverage. The cap binds on most M1 trades (a 1-2 pip stop cannot be sized to 1% risk on a $10k account at 30:1), which is itself a finding.
* **Statistics:** expectancy per trade in pips/points and in R (net result / initial stop distance); profit factor; max drawdown in pips and in % of the 1%-risk equity curve; Sharpe = annualised mean/std of daily P&L (pips, 1 lot, zeros on no-trade days); longest losing streak; 95% percentile-bootstrap CI (2,000 resamples of the trade list) for the mean net pips per trade; breakdown by calendar year, by entry session (Asia 22-07, London 07-13, New York 13-22 UTC) and by sample half (split at the midpoint 2025-06-03; nothing was optimised on either half).
* **Random baseline (G):** at each bar a trade opens with probability 1/100 (M5) or 1/300 (M1), direction by coin flip, SL = TP = 1 x ATR(14); 50 seeds per symbol / timeframe / cost case.

### Strategy definitions as implemented

| ID | Strategy | Rules used |
|---|---|---|
| A | EMA pullback trend scalp | EMA fast/slow (9/21 and 5/13) plus EMA50 on the signal TF. Long when fast > slow, close > EMA50, the bar's low touched the fast EMA and the bar closed back above it with close > open (mirror for shorts). SL = 1.5 x ATR(14); TP = 1.0 x or 1.5 x the stop distance. Run on M5 (as specified) and M1. |
| B | Bollinger Band mean reversion | BB(20, 2). Long when the previous close was below the lower band and this close is back inside (and still below the middle band); mirror for shorts. TP = middle band at signal time; SL = 1 x ATR beyond the band. Variant with RSI(14) < 30 / > 70 on the outside bar. M1 and M5. |
| C | Asian-range London breakout | Range = high/low of 00:00-07:00 UTC. Buy stop at high + 2 pips (gold: + 20 points), sell stop at low - 2 pips, active 07:00-10:00 UTC, other order cancelled on fill, one trade per day. SL = opposite side of the range (capped at 1.5 x range from entry); TP = 1 x range; forced flat at 12:00 UTC. |
| D | NY opening-range breakout | Range = first 15 min (gold) / 30 min (EURUSD) from 13:30 UTC as specified, plus a DST-aware variant anchored at 09:30 New York time (which is 14:30 UTC in winter). Stop orders at the range extremes, active for 2.5 h; SL = range midpoint; TP = 1 x or 2 x range; flat 3.5 h after the range start (17:00 UTC for the 13:30 anchor). One trade per day. |
| E | RSI(2) extreme mean reversion | Long when RSI(2) < 10 and close > EMA200; exit when RSI(2) > 60 or after 12 bars; SL = 2 x ATR(14). Mirror for shorts (RSI(2) > 90, exit below 40). M5 (as specified) and M1. |
| F | Stochastic + EMA50 crossover | Stochastic(5,3,3): long when %K crosses above %D from below 20 and close > EMA50; mirror for shorts from above 80. SL = TP = 1 x ATR(14). M1 and M5. |
| G | Random baseline | Coin-flip direction, SL = TP = 1 x ATR(14), 50 seeds. |
| H | Session (T)WAP +/- 2 sigma fade | Cumulative session mean of typical price from 00:00 UTC with +/-2 sigma bands; long when the close crosses back above the lower band after closing below it (at least 30 bars into the day); TP = session mean; SL = 1 x ATR beyond the band; flat at 00:00 UTC. M1 only. |

"""

FINDINGS = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'findings.md')).read() \
    if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'findings.md')) else '## 4. Findings\n\n(to be written)\n'

L = [HEADER, FINDINGS, '# 5. Result tables\n', '<!-- tables generated by make_report.py from results CSVs -->\n']

# ---------------------------------------------------------------------------------------------------------------------
L.append('## A. Master results (base cost case)\n')
L.append('Expectancy, net result and drawdown are in the symbol unit (EURUSD: pips; XAUUSD: points = $0.01/oz = $1 per lot). '
         'R = net result divided by the initial stop distance. "Return/MaxDD (1% risk)" is a compounding $10,000 account risking 1% of equity per trade, '
         'position size capped at 30:1 (EURUSD) / 20:1 (XAUUSD) leverage. Sharpe is annualised from daily P&L in pips (fixed 1 lot), zero on no-trade days. '
         '95% CI = percentile bootstrap (2,000 resamples) of the mean net pips per trade; an asterisk marks a CI entirely above zero.\n')
for sym in ('EURUSD', 'XAUUSD'):
    m = master[(master.symbol == sym) & (master.cost_case == 'base')]
    L.append(f'### {sym} — base costs ({m.cost_pips.iloc[0]:g} {UNIT[sym]} round trip)\n')
    rows = []
    for _, r in m.iterrows():
        rows.append([r.strategy, r.tf, f'{int(r.trades):,}', f(r.win_rate, 1), f(r.profit_factor), f(r.exp_pips), f(r.exp_R),
                     f(r.net_pips, 0), f(r.max_dd_pips, 0), f(r.return_pct_1pct_risk, 1), f(r.max_dd_pct_1pct_risk, 1),
                     f(r.sharpe, 1), ci(r.ci_lo, r.ci_hi), f(r.avg_risk_pips, 1), f(r.cost_pct_of_risk, 0)])
    L.append(md_table(rows, ['Strategy', 'TF', 'Trades', 'Win %', 'PF', 'Exp (unit)', 'Exp (R)', 'Net (unit)', 'MaxDD (unit)',
                             'Return % (1% risk)', 'MaxDD % (1% risk)', 'Sharpe', '95% CI exp (unit)', 'Avg stop (unit)', 'Cost as % of stop']))
    L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## B. Cost sensitivity: expectancy per trade and profit factor under each cost case\n')
L.append('gross = no costs at all; cheap / base / expensive as defined in the cost assumptions. Expectancy in the symbol unit; PF in brackets.\n')
for sym in ('EURUSD', 'XAUUSD'):
    m = master[master.symbol == sym]
    costs = {c: m[m.cost_case == c].cost_pips.iloc[0] for c in ORDER}
    L.append(f'### {sym}\n')
    rows = []
    for (strat, tf), g in m.groupby(['strategy', 'tf'], sort=False):
        row = [strat, tf, f'{int(g.trades.iloc[0]):,}']
        for c in ORDER:
            r = g[g.cost_case == c].iloc[0]
            row.append(f'{r.exp_pips:+.2f} ({f(r.profit_factor)})')
        rows.append(row)
    L.append(md_table(rows, ['Strategy', 'TF', 'Trades'] + [f'{c} ({costs[c]:g})' for c in ORDER]))
    L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## C. Results by year (base cost case)\n')
L.append('Expectancy per trade (unit) and profit factor, with trade count. 2026 runs to 4 Nov 2026.\n')
for sym in ('EURUSD', 'XAUUSD'):
    y = by_year[(by_year.symbol == sym) & (by_year.cost_case == 'base')]
    L.append(f'### {sym}\n')
    rows = []
    for (strat, tf), g in y.groupby(['strategy', 'tf'], sort=False):
        row = [strat, tf]
        for yr in (2024, 2025, 2026):
            r = g[g.year == yr]
            if len(r):
                r = r.iloc[0]
                row.append(f'{r.exp_pips:+.2f} / {f(r.profit_factor)} / {int(r.trades):,}')
            else:
                row.append('-')
        gm = master[(master.symbol == sym) & (master.strategy == strat) & (master.tf == tf) & (master.cost_case == 'gross')].iloc[0]
        row.append(f'{gm.exp_pips:+.2f}')
        rows.append(row)
    L.append(md_table(rows, ['Strategy', 'TF', '2024 exp / PF / n', '2025 exp / PF / n', '2026 exp / PF / n', 'Gross exp (all years)']))
    L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## D. Walk-forward split: first half vs second half (base cost case)\n')
L.append(f'No parameters were optimised; the sample is simply split at its midpoint ({info["EURUSD"]["mid_point"][:10]}). Expectancy per trade with 95% bootstrap CI.\n')
for sym in ('EURUSD', 'XAUUSD'):
    h = by_half[(by_half.symbol == sym) & (by_half.cost_case == 'base')]
    L.append(f'### {sym}\n')
    rows = []
    for (strat, tf), g in h.groupby(['strategy', 'tf'], sort=False):
        a = g[g.half == 'H1']; b = g[g.half == 'H2']
        a = a.iloc[0] if len(a) else None; b = b.iloc[0] if len(b) else None
        rows.append([strat, tf,
                     f'{int(a.trades):,}' if a is not None else '-', f'{a.exp_pips:+.2f} {ci(a.ci_lo, a.ci_hi)}' if a is not None else '-', f(a.profit_factor) if a is not None else '-',
                     f'{int(b.trades):,}' if b is not None else '-', f'{b.exp_pips:+.2f} {ci(b.ci_lo, b.ci_hi)}' if b is not None else '-', f(b.profit_factor) if b is not None else '-'])
    L.append(md_table(rows, ['Strategy', 'TF', 'H1 trades', 'H1 exp [CI]', 'H1 PF', 'H2 trades', 'H2 exp [CI]', 'H2 PF']))
    L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## E. Results by session (base cost case; strategies A, B, E, F, H)\n')
L.append('Session of the entry time (UTC): Asia 22:00-07:00, London 07:00-13:00, New York 13:00-22:00. Expectancy per trade (unit) / PF / trades.\n')
for sym in ('EURUSD', 'XAUUSD'):
    s = by_sess[(by_sess.symbol == sym) & (by_sess.cost_case == 'base')]
    L.append(f'### {sym}\n')
    rows = []
    for (strat, tf), g in s.groupby(['strategy', 'tf'], sort=False):
        row = [strat, tf]
        for ses in ('Asia', 'London', 'NY'):
            r = g[g.session == ses]
            if len(r) and r.iloc[0].trades > 0:
                r = r.iloc[0]
                row.append(f'{r.exp_pips:+.2f} / {f(r.profit_factor)} / {int(r.trades):,}' + (' *' if (not np.isnan(r.ci_lo)) and r.ci_lo > 0 else ''))
            else:
                row.append('-')
        rows.append(row)
    L.append(md_table(rows, ['Strategy', 'TF', 'Asia', 'London', 'NY']))
    L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## F. Random-entry baseline (strategy G: coin-flip direction, SL = TP = 1 x ATR(14), 50 seeds)\n')
L.append('Mean across seeds, with the share of seeds that finished with a positive net result. This shows the pure cost drag a scalper must overcome.\n')
rows = []
for (sym, tf, cc), g in rnd.groupby(['symbol', 'tf', 'cost_case'], sort=False):
    g = g.set_index('seed')
    rows.append([sym, tf, cc, f'{g.cost_pips.iloc[0]:g}', f'{g.trades.mean():,.0f}', f(g.win_rate.mean(), 1), f(g.exp_pips.mean(), 2),
                 f'[{g.exp_pips.quantile(0.05):+.2f}, {g.exp_pips.quantile(0.95):+.2f}]', f(g.exp_R.mean(), 2), f(g.profit_factor.mean(), 2),
                 f'{(g.net_pips > 0).mean()*100:.0f}%', f(g.avg_risk_pips.mean(), 1)])
rows.sort(key=lambda r: (r[0], r[1], ORDER.index(r[2])))
L.append(md_table(rows, ['Symbol', 'TF', 'Cost case', 'Cost (unit)', 'Trades/seed', 'Win %', 'Mean exp (unit)', '5-95% of seeds', 'Mean exp (R)', 'Mean PF', 'Seeds > 0', 'Avg stop (unit)']))
L.append('')

# ---------------------------------------------------------------------------------------------------------------------
L.append('## G. Which results have a confidence interval above zero?\n')
pos = master[(master.ci_lo > 0)]
if len(pos):
    rows = [[r.symbol, r.strategy, r.tf, r.cost_case, f'{int(r.trades):,}', f'{r.exp_pips:+.2f}', ci(r.ci_lo, r.ci_hi), f(r.profit_factor)] for _, r in pos.iterrows()]
    L.append(md_table(rows, ['Symbol', 'Strategy', 'TF', 'Cost case', 'Trades', 'Exp (unit)', '95% CI', 'PF']))
else:
    L.append('None. No strategy/symbol/timeframe/cost-case combination has a bootstrap 95% CI for expectancy that excludes zero on the positive side.')
L.append('')
# also list positive point estimates after costs even if CI straddles zero
pp = master[(master.cost_case != 'gross') & (master.exp_pips > 0)]
L.append('Positive point estimates after costs (CI may include zero):\n')
if len(pp):
    rows = [[r.symbol, r.strategy, r.tf, r.cost_case, f'{int(r.trades):,}', f'{r.exp_pips:+.2f}', ci(r.ci_lo, r.ci_hi), f(r.profit_factor), f(r.sharpe, 2)] for _, r in pp.iterrows()]
    L.append(md_table(rows, ['Symbol', 'Strategy', 'TF', 'Cost case', 'Trades', 'Exp (unit)', '95% CI', 'PF', 'Sharpe']))
else:
    L.append('None.')
L.append('')

open(out_md, 'w').write('\n'.join(L))
print('wrote', out_md, len(L), 'lines')
